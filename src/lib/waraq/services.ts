export function placesFor(city: string): Place[] {
  const c = city || "مدينتك";
  return PLACE_TEMPLATES.map((p, i) => ({
    ...p,
    id: `place-${i}`,
    address: `${c} – عنوان تجريبي ${i + 1}`,
    mapQuery: `${p.name} ${c}`,
  }));
}

