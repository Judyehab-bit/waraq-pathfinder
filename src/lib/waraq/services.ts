export function getService(id: string) {
  return SERVICES.find((s) => s.id === id);
}

/** Questions that apply given current answers. */
export function visibleQuestions(service: Service, answers: Record<string, string>) {
  return service.questions.filter((q) => !q.showIf || q.showIf(answers));
}

export function requiredDocsFor(service: Service, answers: Record<string, string>): DocumentDetail[] {
  return service.requiredDocuments
    .filter((r) => !r.showIf || r.showIf(answers))
    .map((r) => service.documents[r.docId])
    .filter((d): d is DocumentDetail => Boolean(d));
}

export function stepsFor(service: Service, answers: Record<string, string>) {
  return service.steps.filter((s) => !s.showIf || s.showIf(answers));
}
